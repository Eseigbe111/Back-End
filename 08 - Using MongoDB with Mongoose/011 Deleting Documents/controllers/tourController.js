//// Fc for Handling Delete request.
exports.deleteTour = async (req, res) => {
  try {
    // This will be pretty similar to updateTour()
    // So in this case we actually don't save anything in a variable bcos we actually don't
    // send anything back to the client. So in the REST API, it is a common practice not to
    // send any data to the client when there is a delete operatn.
    // To try this we just need to create a tour in the Postman app ad delete it.

    await Tour.findByIdAndDelete(req.params.id);

    res.status(204).json({
      status: 'success',
      data: null, // The data is null to show that the data no longer exists
    });
  } catch (err) {
    // We will handle these errors well in the next section
    res.status(404).json({
      status: 'fail',
      message: err,
    });
  }
};

